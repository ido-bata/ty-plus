//! Product-owned, count- and size-bounded retention policies.

use std::{
    fmt,
    path::{Component, Path, PathBuf},
};

use serde::{Deserialize, Serialize};
use ty_plus_host_filesystem::platform::{list_directory, read_entry, remove_entry};

use crate::{MutationContext, RegisteredPath, Transaction};

/// Errors returned when a retention value is outside its product contract.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RetentionError {
    /// Operation history count is outside `0..=500`.
    OperationHistoryCountOutOfRange { value: usize },
    /// The policy history count is outside the public `u32` contract.
    HistoryCountOutOfRange { value: u32 },
    /// The worker log file count exceeds the storage-owned cap.
    WorkerLogFilesOutOfRange { value: u32 },
    /// The worker log byte cap exceeds the storage-owned cap.
    WorkerLogBytesOutOfRange { value: u64 },
    /// The diagnostic byte cap exceeds the storage-owned cap.
    DiagnosticBytesOutOfRange { value: u64 },
    /// Snapshot count is outside `1..=100`.
    SnapshotCountOutOfRange { value: usize },
    /// A generated diagnostic bundle exceeds 10 MiB.
    DiagnosticBundleTooLarge { size_bytes: u64 },
}

impl fmt::Display for RetentionError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::OperationHistoryCountOutOfRange { value } => {
                write!(f, "operation history count {value} is outside 0..=500")
            }
            Self::HistoryCountOutOfRange { value } => {
                write!(f, "history count {value} is outside 0..=500")
            }
            Self::WorkerLogFilesOutOfRange { value } => {
                write!(f, "worker log file count {value} exceeds 5")
            }
            Self::WorkerLogBytesOutOfRange { value } => {
                write!(f, "worker log byte cap {value} exceeds 5242880")
            }
            Self::DiagnosticBytesOutOfRange { value } => {
                write!(f, "diagnostic byte cap {value} exceeds 10485760")
            }
            Self::SnapshotCountOutOfRange { value } => {
                write!(f, "snapshot count {value} is outside 1..=100")
            }
            Self::DiagnosticBundleTooLarge { size_bytes } => {
                write!(f, "diagnostic bundle size {size_bytes} exceeds 10 MiB")
            }
        }
    }
}

impl std::error::Error for RetentionError {}

/// Default operation history entry count.
pub const OPERATION_HISTORY_DEFAULT_ENTRIES: usize = 100;
/// Inclusive maximum operation history entry count.
pub const OPERATION_HISTORY_MAX_ENTRIES: usize = 500;
/// Default named workspace snapshot count.
pub const SNAPSHOT_DEFAULT_COUNT: usize = 10;
/// Inclusive maximum named workspace snapshot count.
pub const SNAPSHOT_MAX_COUNT: usize = 100;
/// Maximum number of runtime log files, including the active file.
pub const RUNTIME_LOG_MAX_FILES: usize = 5;
/// Maximum size of one runtime log file.
pub const RUNTIME_LOG_MAX_FILE_BYTES: u64 = 1024 * 1024;
/// Maximum total size of runtime log files.
pub const RUNTIME_LOG_MAX_TOTAL_BYTES: u64 = 5 * 1024 * 1024;
/// Managed diagnostic bundle count. Bundles are exporter outputs, not state.
pub const DIAGNOSTIC_MANAGED_RETAINED_BUNDLES: usize = 0;
/// Maximum generated diagnostic bundle size.
pub const DIAGNOSTIC_MAX_GENERATED_BYTES: u64 = 10 * 1024 * 1024;

/// A storage-owned retention policy. It deliberately has no time-to-live
/// field: state remains until an explicit delete, clear, or reset operation.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct RetentionPolicy {
    /// Maximum persisted operation history entries. Zero disables new writes.
    history_count: u32,
    /// Maximum named workspace snapshots.
    snapshot_count: u32,
    /// Maximum worker log files retained by the logger.
    worker_log_files: u32,
    /// Maximum total worker log bytes.
    worker_log_bytes: u64,
    /// Maximum diagnostic bundle bytes generated by one export.
    diagnostic_bytes: u64,
}

impl RetentionPolicy {
    /// Validates all policy values against storage-owned hard maxima.
    pub fn new(
        history_count: u32,
        snapshot_count: u32,
        worker_log_files: u32,
        worker_log_bytes: u64,
        diagnostic_bytes: u64,
    ) -> Result<Self, RetentionError> {
        if history_count > OPERATION_HISTORY_MAX_ENTRIES as u32 {
            return Err(RetentionError::HistoryCountOutOfRange {
                value: history_count,
            });
        }
        if !(1..=SNAPSHOT_MAX_COUNT as u32).contains(&snapshot_count) {
            return Err(RetentionError::SnapshotCountOutOfRange {
                value: snapshot_count as usize,
            });
        }
        if worker_log_files > RUNTIME_LOG_MAX_FILES as u32 {
            return Err(RetentionError::WorkerLogFilesOutOfRange {
                value: worker_log_files,
            });
        }
        if worker_log_bytes > RUNTIME_LOG_MAX_TOTAL_BYTES {
            return Err(RetentionError::WorkerLogBytesOutOfRange {
                value: worker_log_bytes,
            });
        }
        if diagnostic_bytes > DIAGNOSTIC_MAX_GENERATED_BYTES {
            return Err(RetentionError::DiagnosticBytesOutOfRange {
                value: diagnostic_bytes,
            });
        }
        Ok(Self {
            history_count,
            snapshot_count,
            worker_log_files,
            worker_log_bytes,
            diagnostic_bytes,
        })
    }

    /// Returns the validated history entry cap.
    #[must_use]
    pub const fn history_count(self) -> u32 {
        self.history_count
    }

    /// Returns the validated snapshot cap.
    #[must_use]
    pub const fn snapshot_count(self) -> u32 {
        self.snapshot_count
    }

    /// Returns the validated worker log file cap.
    #[must_use]
    pub const fn worker_log_files(self) -> u32 {
        self.worker_log_files
    }

    /// Returns the validated worker log byte cap.
    #[must_use]
    pub const fn worker_log_bytes(self) -> u64 {
        self.worker_log_bytes
    }

    /// Returns the validated diagnostic byte cap.
    #[must_use]
    pub const fn diagnostic_bytes(self) -> u64 {
        self.diagnostic_bytes
    }
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct RetentionPolicyInput {
    history_count: u32,
    snapshot_count: u32,
    worker_log_files: u32,
    worker_log_bytes: u64,
    diagnostic_bytes: u64,
}

impl<'de> Deserialize<'de> for RetentionPolicy {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        let input = RetentionPolicyInput::deserialize(deserializer)?;
        Self::new(
            input.history_count,
            input.snapshot_count,
            input.worker_log_files,
            input.worker_log_bytes,
            input.diagnostic_bytes,
        )
        .map_err(serde::de::Error::custom)
    }
}

impl Default for RetentionPolicy {
    fn default() -> Self {
        Self::new(
            OPERATION_HISTORY_DEFAULT_ENTRIES as u32,
            SNAPSHOT_DEFAULT_COUNT as u32,
            RUNTIME_LOG_MAX_FILES as u32,
            RUNTIME_LOG_MAX_TOTAL_BYTES,
            DIAGNOSTIC_MAX_GENERATED_BYTES,
        )
        .expect("built-in retention policy is valid")
    }
}

/// Validated operation history retention count.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OperationHistoryLimit(usize);

impl OperationHistoryLimit {
    /// Validates an operation history count in the inclusive product range.
    pub fn new(value: usize) -> Result<Self, RetentionError> {
        if value <= OPERATION_HISTORY_MAX_ENTRIES {
            Ok(Self(value))
        } else {
            Err(RetentionError::OperationHistoryCountOutOfRange { value })
        }
    }

    /// Returns the validated count.
    #[must_use]
    pub const fn get(self) -> usize {
        self.0
    }

    /// Returns whether persisted recovery entries are disabled.
    #[must_use]
    pub const fn is_disabled(self) -> bool {
        self.0 == 0
    }
}

impl Default for OperationHistoryLimit {
    fn default() -> Self {
        Self(OPERATION_HISTORY_DEFAULT_ENTRIES)
    }
}

/// Validated named workspace snapshot retention count.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SnapshotLimit(usize);

impl SnapshotLimit {
    /// Validates a snapshot count in the inclusive product range.
    pub fn new(value: usize) -> Result<Self, RetentionError> {
        if (1..=SNAPSHOT_MAX_COUNT).contains(&value) {
            Ok(Self(value))
        } else {
            Err(RetentionError::SnapshotCountOutOfRange { value })
        }
    }

    /// Returns the validated count.
    #[must_use]
    pub const fn get(self) -> usize {
        self.0
    }
}

impl Default for SnapshotLimit {
    fn default() -> Self {
        Self(SNAPSHOT_DEFAULT_COUNT)
    }
}

/// Runtime log rotation policy. Filesystem logging is owned by a future logger.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RuntimeLogPolicy {
    max_files: u32,
    max_file_bytes: u64,
    max_total_bytes: u64,
}

impl RuntimeLogPolicy {
    /// Builds a logger policy from an already validated retention policy.
    #[must_use]
    pub const fn from_policy(policy: RetentionPolicy) -> Self {
        Self {
            max_files: policy.worker_log_files,
            max_file_bytes: if RUNTIME_LOG_MAX_FILE_BYTES < policy.worker_log_bytes {
                RUNTIME_LOG_MAX_FILE_BYTES
            } else {
                policy.worker_log_bytes
            },
            max_total_bytes: policy.worker_log_bytes,
        }
    }

    /// Decides whether a logger must rotate before writing another chunk.
    #[must_use]
    pub const fn should_rotate(self, active_file_bytes: u64, file_count: usize) -> bool {
        active_file_bytes >= self.max_file_bytes || file_count as u32 >= self.max_files
    }

    /// Returns the explicit total byte cap for the future logger.
    #[must_use]
    pub const fn max_total_bytes(self) -> u64 {
        self.max_total_bytes
    }

    /// Returns the configured file count cap.
    #[must_use]
    pub const fn max_files(self) -> u32 {
        self.max_files
    }

    /// Returns the maximum size of one log file.
    #[must_use]
    pub const fn max_file_bytes(self) -> u64 {
        self.max_file_bytes
    }
}

impl Default for RuntimeLogPolicy {
    fn default() -> Self {
        Self::from_policy(RetentionPolicy::default())
    }
}

/// Diagnostic bundle generation policy. Exported bundles have no automatic
/// retention; the managed boundary performs only explicit create and clear.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DiagnosticBundlePolicy {
    max_bytes: u64,
}

impl DiagnosticBundlePolicy {
    /// Builds a diagnostic policy from an already validated retention policy.
    #[must_use]
    pub const fn from_policy(policy: RetentionPolicy) -> Self {
        Self {
            max_bytes: policy.diagnostic_bytes,
        }
    }

    /// Validates a generated bundle size.
    pub fn validate_generated_size(self, size_bytes: u64) -> Result<(), RetentionError> {
        if size_bytes <= self.max_bytes {
            Ok(())
        } else {
            Err(RetentionError::DiagnosticBundleTooLarge { size_bytes })
        }
    }

    /// Returns the managed retained bundle count.
    #[must_use]
    pub const fn managed_retained_bundle_count(self) -> usize {
        DIAGNOSTIC_MANAGED_RETAINED_BUNDLES
    }

    /// Returns the configured diagnostic byte cap.
    #[must_use]
    pub const fn max_bytes(self) -> u64 {
        self.max_bytes
    }
}

impl Default for DiagnosticBundlePolicy {
    fn default() -> Self {
        Self::from_policy(RetentionPolicy::default())
    }
}

/// Errors returned by managed retention stores.
#[derive(Debug)]
pub enum RetentionStoreError {
    /// A path or filename was not an owned safe relative entry.
    InvalidPath(PathBuf),
    /// The managed capability rejected an I/O operation.
    Io(std::io::Error),
    /// A new entry exceeds the configured byte cap.
    FileTooLarge { actual: u64, maximum: u64 },
    /// Existing state cannot be represented within the configured cap.
    RetentionOverflow,
    /// A save would exceed the configured count or byte cap.
    CapacityExceeded {
        files: u64,
        bytes: u64,
        max_files: u32,
        max_bytes: u64,
    },
    /// An unexpected entry was found in the managed log directory.
    UnknownEntry(PathBuf),
}

impl fmt::Display for RetentionStoreError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidPath(path) => {
                write!(formatter, "invalid retention path: {}", path.display())
            }
            Self::Io(error) => write!(formatter, "retention I/O failed: {error}"),
            Self::FileTooLarge { actual, maximum } => {
                write!(
                    formatter,
                    "retention entry is {actual} bytes; maximum is {maximum}"
                )
            }
            Self::RetentionOverflow => formatter.write_str("retention size arithmetic overflow"),
            Self::CapacityExceeded {
                files,
                bytes,
                max_files,
                max_bytes,
            } => write!(
                formatter,
                "retention capacity exceeded: {files} files/{bytes} bytes; maximum is {max_files} files/{max_bytes} bytes"
            ),
            Self::UnknownEntry(path) => {
                write!(
                    formatter,
                    "unknown managed retention entry: {}",
                    path.display()
                )
            }
        }
    }
}

impl std::error::Error for RetentionStoreError {}

impl From<std::io::Error> for RetentionStoreError {
    fn from(error: std::io::Error) -> Self {
        Self::Io(error)
    }
}

fn write_managed_bytes(
    context: &MutationContext<'_>,
    destination: RegisteredPath,
    bytes: &[u8],
) -> Result<(), RetentionStoreError> {
    let mut transaction = Transaction::prepare(
        context.guard(),
        destination,
        context.invocation_id().clone(),
    )
    .map_err(|error| RetentionStoreError::Io(std::io::Error::other(error.to_string())))?;
    transaction
        .write_all(bytes)
        .and_then(|_| transaction.flush())
        .and_then(|_| transaction.commit().map(|_| ()))
        .map_err(|error| RetentionStoreError::Io(std::io::Error::other(error.to_string())))
}

fn safe_single_component_name(name: &str, extension: &str) -> Result<PathBuf, RetentionStoreError> {
    let path = Path::new(name);
    let mut components = path.components();
    let Some(Component::Normal(component)) = components.next() else {
        return Err(RetentionStoreError::InvalidPath(path.to_path_buf()));
    };
    if components.next().is_some()
        || component.to_string_lossy().is_empty()
        || !component.to_string_lossy().ends_with(extension)
    {
        return Err(RetentionStoreError::InvalidPath(path.to_path_buf()));
    }
    Ok(PathBuf::from(component))
}

/// Managed worker-log persistence and count/byte pruning.
#[derive(Debug, Clone, Copy)]
pub struct WorkerLogStore {
    policy: RuntimeLogPolicy,
}

impl WorkerLogStore {
    /// Creates a worker-log store from validated retention values.
    #[must_use]
    pub const fn new(policy: RuntimeLogPolicy) -> Self {
        Self { policy }
    }

    /// Writes one log file when the resulting state fits the policy caps.
    pub fn write_with_context(
        &self,
        context: &MutationContext<'_>,
        name: &str,
        bytes: &[u8],
    ) -> Result<usize, RetentionStoreError> {
        let name = safe_single_component_name(name, ".log")?;
        let actual =
            u64::try_from(bytes.len()).map_err(|_| RetentionStoreError::RetentionOverflow)?;
        if actual > self.policy.max_file_bytes() {
            return Err(RetentionStoreError::FileTooLarge {
                actual,
                maximum: self.policy.max_file_bytes(),
            });
        }
        let (existing, total) = self.inspect_with_context(context)?;
        let previous = existing
            .iter()
            .find(|(existing_name, _)| existing_name == &name)
            .map(|(_, size)| *size);
        let files = u64::try_from(existing.len())
            .map_err(|_| RetentionStoreError::RetentionOverflow)?
            .checked_add(u64::from(previous.is_none()))
            .ok_or(RetentionStoreError::RetentionOverflow)?;
        let previous_size = previous.unwrap_or(0);
        let result_bytes = total
            .checked_sub(previous_size)
            .and_then(|value| value.checked_add(actual))
            .ok_or(RetentionStoreError::RetentionOverflow)?;
        if files > u64::from(self.policy.max_files())
            || result_bytes > self.policy.max_total_bytes()
        {
            return Err(RetentionStoreError::CapacityExceeded {
                files,
                bytes: result_bytes,
                max_files: self.policy.max_files(),
                max_bytes: self.policy.max_total_bytes(),
            });
        }
        let destination = RegisteredPath::new(Path::new("logs").join(name))
            .map_err(|_| RetentionStoreError::InvalidPath(PathBuf::from("logs")))?;
        write_managed_bytes(context, destination, bytes)?;
        Ok(0)
    }

    /// Explicitly rotates old log files until count and byte caps are met.
    pub fn rotate_with_context(
        &self,
        context: &MutationContext<'_>,
    ) -> Result<usize, RetentionStoreError> {
        self.prune_with_context(context)
    }

    /// Applies count and total-byte caps to the managed log directory after
    /// an explicit rotation request.
    pub fn prune_with_context(
        &self,
        context: &MutationContext<'_>,
    ) -> Result<usize, RetentionStoreError> {
        let (mut sized, mut total) = self.inspect_with_context(context)?;
        let max_files = u64::from(self.policy.max_files());
        let mut removed = 0;
        while (u64::try_from(sized.len()).map_err(|_| RetentionStoreError::RetentionOverflow)?
            > max_files)
            || total > self.policy.max_total_bytes()
        {
            let Some((name, size)) = sized.first().cloned() else {
                return Err(RetentionStoreError::RetentionOverflow);
            };
            let relative = RegisteredPath::new(Path::new("logs").join(&name))
                .map_err(|_| RetentionStoreError::InvalidPath(PathBuf::from("logs")))?;
            remove_entry(context.guard().managed_root().as_path(), relative.as_path())
                .map_err(RetentionStoreError::Io)?;
            let revision = RegisteredPath::new(
                Path::new("logs").join(Path::new(&name).with_extension("rev.json")),
            )
            .map_err(|_| RetentionStoreError::InvalidPath(PathBuf::from("logs")))?;
            match remove_entry(context.guard().managed_root().as_path(), revision.as_path()) {
                Ok(()) => {}
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
                Err(error) => return Err(RetentionStoreError::Io(error)),
            }
            total = total
                .checked_sub(size)
                .ok_or(RetentionStoreError::RetentionOverflow)?;
            sized.remove(0);
            removed += 1;
        }
        Ok(removed)
    }

    fn inspect_with_context(
        &self,
        context: &MutationContext<'_>,
    ) -> Result<(Vec<(PathBuf, u64)>, u64), RetentionStoreError> {
        let root = context.guard().managed_root().as_path();
        let directory = RegisteredPath::new("logs")
            .map_err(|_| RetentionStoreError::InvalidPath(PathBuf::from("logs")))?;
        let mut entries = match list_directory(root, directory.as_path()) {
            Ok(entries) => entries,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                return Ok((Vec::new(), 0))
            }
            Err(error) => return Err(RetentionStoreError::Io(error)),
        };
        entries.sort();
        let entry_names = entries
            .iter()
            .map(|entry| entry.to_string_lossy().into_owned())
            .collect::<std::collections::BTreeSet<_>>();
        let mut sized = Vec::with_capacity(entries.len());
        let mut total = 0_u64;
        for entry in entries {
            let name = entry.to_string_lossy().into_owned();
            if let Some(stem) = name.strip_suffix(".rev.json") {
                let companion = format!("{stem}.log");
                if stem.is_empty() || !entry_names.contains(&companion) {
                    return Err(RetentionStoreError::UnknownEntry(PathBuf::from(name)));
                }
                let revision = RegisteredPath::new(directory.as_path().join(&name))
                    .map_err(|_| RetentionStoreError::InvalidPath(PathBuf::from(&name)))?;
                read_entry(root, revision.as_path()).map_err(RetentionStoreError::Io)?;
                continue;
            }
            let name = safe_single_component_name(&name, ".log")?;
            let relative = RegisteredPath::new(directory.as_path().join(&name))
                .map_err(|_| RetentionStoreError::InvalidPath(name.clone()))?;
            let bytes = read_entry(root, relative.as_path()).map_err(RetentionStoreError::Io)?;
            let size =
                u64::try_from(bytes.len()).map_err(|_| RetentionStoreError::RetentionOverflow)?;
            if size > self.policy.max_total_bytes() {
                return Err(RetentionStoreError::FileTooLarge {
                    actual: size,
                    maximum: self.policy.max_total_bytes(),
                });
            }
            total = total
                .checked_add(size)
                .ok_or(RetentionStoreError::RetentionOverflow)?;
            sized.push((name, size));
        }
        Ok((sized, total))
    }
}

/// Managed diagnostic-bundle generation boundary.
#[derive(Debug, Clone, Copy)]
pub struct DiagnosticBundleStore {
    policy: DiagnosticBundlePolicy,
}

impl DiagnosticBundleStore {
    /// Creates a diagnostic store from validated retention values.
    #[must_use]
    pub const fn new(policy: DiagnosticBundlePolicy) -> Self {
        Self { policy }
    }

    /// Creates a managed diagnostic bundle only after byte validation.
    pub fn create_with_context(
        &self,
        context: &MutationContext<'_>,
        destination: RegisteredPath,
        bytes: &[u8],
    ) -> Result<(), RetentionStoreError> {
        let components = destination.as_path().components().collect::<Vec<_>>();
        if components.len() != 2
            || components[0] != Component::Normal(std::ffi::OsStr::new("diagnostics"))
            || !matches!(components[1], Component::Normal(_))
        {
            return Err(RetentionStoreError::InvalidPath(
                destination.as_path().to_path_buf(),
            ));
        }
        let actual =
            u64::try_from(bytes.len()).map_err(|_| RetentionStoreError::RetentionOverflow)?;
        self.policy.validate_generated_size(actual).map_err(|_| {
            RetentionStoreError::FileTooLarge {
                actual,
                maximum: self.policy.max_bytes(),
            }
        })?;
        write_managed_bytes(context, destination, bytes)
    }

    /// Explicitly removes a generated diagnostic bundle and its revision.
    pub fn clear_with_context(
        &self,
        context: &MutationContext<'_>,
        destination: RegisteredPath,
    ) -> Result<bool, RetentionStoreError> {
        let root = context.guard().managed_root().as_path();
        let components = destination.as_path().components().collect::<Vec<_>>();
        if components.len() != 2
            || components[0] != Component::Normal(std::ffi::OsStr::new("diagnostics"))
            || !matches!(components[1], Component::Normal(_))
        {
            return Err(RetentionStoreError::InvalidPath(
                destination.as_path().to_path_buf(),
            ));
        }
        let mut removed = false;
        for relative in [
            destination.as_path().to_path_buf(),
            destination.as_path().with_extension("rev.json"),
        ] {
            match remove_entry(root, &relative) {
                Ok(()) => removed = true,
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
                Err(error) => return Err(RetentionStoreError::Io(error)),
            }
        }
        Ok(removed)
    }
}

#[cfg(test)]
mod tests {
    use super::{DiagnosticBundlePolicy, RetentionPolicy, RuntimeLogPolicy};

    #[test]
    fn runtime_log_rotation_is_bounded_by_file_and_byte_caps() {
        let policy = RuntimeLogPolicy::from_policy(RetentionPolicy::default());

        assert!(policy.should_rotate(1024 * 1024, 1));
        assert!(policy.should_rotate(1, 5));
        assert!(!policy.should_rotate(1024 * 1024 - 1, 4));
        assert_eq!(policy.max_total_bytes(), 5 * 1024 * 1024);
    }

    #[test]
    fn diagnostic_bundle_policy_rejects_oversized_generated_bundles() {
        let policy = DiagnosticBundlePolicy::from_policy(RetentionPolicy::default());

        assert!(policy.validate_generated_size(10 * 1024 * 1024).is_ok());
        assert!(policy
            .validate_generated_size(10 * 1024 * 1024 + 1)
            .is_err());
        assert_eq!(policy.managed_retained_bundle_count(), 0);
    }
}
